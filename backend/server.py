import os
import subprocess
import tempfile
from flask import Flask, request, send_file, jsonify

app = Flask(__name__)

@app.route("/health", methods=["GET"])
def health():
    return jsonify({
        "status": "ok",
        "service": "documate-libreoffice-converter",
        "version": "1.0.0"
    })

@app.route("/api/v1/convert", methods=["POST"])
def convert():
    if "file" not in request.files:
        return jsonify({"error": "No file uploaded in 'file' multipart field"}), 400

    uploaded_file = request.files["file"]
    if not uploaded_file.filename:
        return jsonify({"error": "Empty filename provided"}), 400

    original_filename = uploaded_file.filename
    base_name = os.path.splitext(original_filename)[0]

    with tempfile.TemporaryDirectory() as temp_dir:
        input_path = os.path.join(temp_dir, original_filename)
        uploaded_file.save(input_path)

        # Execute headless LibreOffice conversion
        cmd = [
            "libreoffice",
            "--headless",
            "--convert-to", "pdf",
            "--outdir", temp_dir,
            input_path
        ]

        try:
            proc = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=90)
            if proc.returncode != 0:
                err_msg = proc.stderr.decode("utf-8", errors="replace")
                return jsonify({"error": "Conversion process failed", "details": err_msg}), 500

            expected_output = os.path.join(temp_dir, f"{base_name}.pdf")
            if not os.path.exists(expected_output):
                # Search for any produced PDF in the temp directory
                pdf_files = [f for f in os.listdir(temp_dir) if f.lower().endswith(".pdf")]
                if pdf_files:
                    expected_output = os.path.join(temp_dir, pdf_files[0])
                else:
                    return jsonify({"error": "Output PDF was not generated by LibreOffice"}), 500

            return send_file(
                expected_output,
                mimetype="application/pdf",
                as_attachment=True,
                download_name=f"{base_name}.pdf"
            )
        except subprocess.TimeoutExpired:
            return jsonify({"error": "Document conversion timed out after 90 seconds"}), 504
        except Exception as e:
            return jsonify({"error": f"Server error: {str(e)}"}), 500

if __name__ == "__main__":
    port = int(os.environ.get("PORT", 8080))
    app.run(host="0.0.0.0", port=port)
